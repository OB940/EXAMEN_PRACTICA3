    private void bGuardarActionPerformed(java.awt.event.ActionEvent evt) {
        String error = ControlErrores.validarMatricula(campoMatricula.getText());
        if (error == null) error = ControlErrores.validarPrecio(campoPrecio.getText());
        if (error == null) error = ControlErrores.validarFecha(campoFecha.getText());
        if (error == null && labelMatricula.getText().isBlank()) error = "ERROR. EL NOMBRE NO PUEDE ESTAR VACÍO.";

        if (error != null) {
            labelError.setForeground(Color.RED);
            labelError.setText(error);
            return;
        }

        String matricula = campoMatricula.getText();
        float precio = Float.parseFloat(campoPrecio.getText().trim().replace(',', '.'));
        LocalDate fecha = LocalDate.parse(campoFecha.getText().trim(), ControlErrores.FORMATO_FECHA);

        lista.añadirCoche(new Coche(matricula, fecha, precio));

        limpiar();
        labelError.setForeground(new Color(0, 128, 0));
        labelError.setText("COCHE " + matricula + " AÑADIDO CORRECTAMENTE.");
    }                                                         

