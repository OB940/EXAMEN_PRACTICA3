    public void refrescar() {
        Coche c = lista.obtenerCocheActual();

        if (c == null) {
            muestraNumero.setText("NO HAY COCHES");
            muestraFecha.setText("-");
            muestraMatricula.setText("-");
            muestraPrecio.setText("-");
        } else {
            muestraNumero.setText("COCHE " + (lista.getActual() + 1) + " DE " + lista.size());
            muestraMatricula.setText(String.valueOf(c.getMatricula()));
            muestraMatricula.setText(c.getMatricula());
            muestraPrecio.setText(String.valueOf(c.getPrecio()));
            muestraFecha.setText(c.getFechaMatriculacion().format(ControlErrores.FORMATO_FECHA));
        }

        boolean hay = !lista.esVacia();
        bPrimero.setEnabled(hay && !lista.esPrimero());
        bRetroceder.setEnabled(hay && !lista.esPrimero());
        bAvanzar.setEnabled(hay && !lista.esUltimo());
        bUltimo.setEnabled(hay && !lista.esUltimo());
        bBorrar.setEnabled(hay);
    }

